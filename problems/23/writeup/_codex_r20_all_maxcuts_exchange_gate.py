"""Exact R20 two-row exchange gate over every connected maximum cut.

For every connected triangle-free graph generated by ``geng -tc``, enumerate
all maximum cuts (up to complementary sides), retain the B-connected cuts with
a nonempty bad-edge set and ``ell = 5`` on every bad edge, and enumerate the
full dependent product of coherent shortest rows.  Every failure of the
row-reserved sameOwner/rowCompanion matcher must admit a strict obligation-
score descent after replacing one or two rows.

Cut identities are canonical side bitmasks: bit ``v`` is the side of vertex
``v``, and the smaller of a mask and its complement is used.  Matching,
scores, cut masks, and all reported counts use integers only.
"""

