#!/usr/bin/env python3
"""Exact audit for the rank-uniform codimension-two hive theorem.

This is a finite consistency check, not the rank-uniform proof.  It rebuilds
the hive rhombus rows for ranks 3 through 20, checks the saturation-index
classification, and evaluates the Berline--Vergne constant of every
nonparallel pair using exact arithmetic.  Rank 3 has a one-dimensional hive
space, so the codimension-two assertion is deliberately reported as not
applicable rather than treated as a nonempty minimum.
"""

from collections import Counter
from fractions import Fraction
from itertools import combinations
from math import gcd


def primitive(row):
    divisor = 0
    for entry in row:
        divisor = gcd(divisor, abs(entry))
    if divisor == 0:
        return None
    return tuple(entry // divisor for entry in row)


def normal_rows(rank):
    interior = [
        (x, y)
        for x in range(1, rank)
        for y in range(1, rank)
        if x + y <= rank - 1
    ]
    coordinate = {point: i for i, point in enumerate(interior)}
    rows = []

    def add(plus, minus):
        row = [0] * len(interior)
        for point in plus:
            if point in coordinate:
                row[coordinate[point]] -= 1
        for point in minus:
            if point in coordinate:
                row[coordinate[point]] += 1
        row = primitive(row)
        if row is not None:
            assert set(row) <= {-1, 0, 1}
            assert sum(entry != 0 for entry in row) <= 4
            rows.append(row)

    for x in range(rank + 1):
        for y in range(rank + 1):
            if x + y <= rank - 2:
                add(
                    [(x + 1, y), (x, y + 1)],
                    [(x, y), (x + 1, y + 1)],
                )
            if y >= 1 and x + y <= rank - 1:
                add(
                    [(x, y), (x + 1, y)],
                    [(x, y + 1), (x + 1, y - 1)],
                )
            if x >= 1 and x + y <= rank - 1:
                add(
                    [(x, y), (x, y + 1)],
                    [(x + 1, y), (x - 1, y + 1)],
                )
    return sorted(set(rows))


def dot(left, right):
    return sum(x * y for x, y in zip(left, right))


def saturation_index(left, right):
    """Index of their span in its saturation; zero means rank below two."""
    divisor = 0
    for i, j in combinations(range(len(left)), 2):
        divisor = gcd(
            divisor,
            abs(left[i] * right[j] - left[j] * right[i]),
        )
    return divisor


def determinant2(left, right):
    return left[0] * right[1] - left[1] * right[0]


def metric_dot(left, right, gram):
    return sum(
        Fraction(left[i]) * gram[i][j] * right[j]
        for i in range(2)
        for j in range(2)
    )


def unimodular_alpha(ray1, ray2, gram):
    """BV constant for a 2-cone generated by a unimodular feasible pair."""
    assert abs(determinant2(ray1, ray2)) == 1
    g11 = metric_dot(ray1, ray1, gram)
    g12 = metric_dot(ray1, ray2, gram)
    g22 = metric_dot(ray2, ray2, gram)
    return Fraction(1, 4) + Fraction(1, 12) * (
        g12 / g11 + g12 / g22
    )


def index1_alpha(normal1, normal2):
    """Use inward feasible rays and the inverse normal Gram matrix."""
    assert saturation_index(normal1, normal2) == 1
    aa = dot(normal1, normal1)
    ab = dot(normal1, normal2)
    bb = dot(normal2, normal2)
    determinant = aa * bb - ab * ab
    assert determinant > 0
    inverse_gram = (
        (Fraction(bb, determinant), Fraction(-ab, determinant)),
        (Fraction(-ab, determinant), Fraction(aa, determinant)),
    )
    value = unimodular_alpha((-1, 0), (0, -1), inverse_gram)
    normal_formula = Fraction(1, 4) - Fraction(ab, 12) * (
        Fraction(1, aa) + Fraction(1, bb)
    )
    assert value == normal_formula

    # The entries are 0,+/-1, so aa and bb are support sizes.  If ab>0,
    # ab<=min(aa,bb), which bounds the parenthesis product by 2.
    assert value >= Fraction(1, 12)
    return value


def index2_alpha(normal1, normal2):
    """Pass to a saturated basis and subdivide the feasible cone exactly."""
    assert saturation_index(normal1, normal2) == 2

    # All 2x2 minors are even.  Since each column lies in {0,+/-1}^2 and
    # the pair has rank two, the nonzero column directions are the two
    # diagonals.  Hence the supports agree and these half-sum vectors are
    # integral, disjointly supported, and form a saturated normal basis.
    assert all((x + y) % 2 == 0 and (x - y) % 2 == 0
               for x, y in zip(normal1, normal2))
    same = tuple((x + y) // 2 for x, y in zip(normal1, normal2))
    opposite = tuple((x - y) // 2 for x, y in zip(normal1, normal2))
    assert saturation_index(same, opposite) == 1
    assert dot(same, opposite) == 0
    aa = dot(same, same)
    bb = dot(opposite, opposite)
    assert aa > 0 and bb > 0 and aa + bb <= 4

    # Coordinates are dual to (same,opposite).  Constraints
    # x+y<=0 and x-y<=0 have extreme feasible rays (-1,1),(-1,-1).
    # Subdivide by (-1,0); BV is a valuation and a primitive ray has
    # constant 1/2.
    inverse_gram = (
        (Fraction(1, aa), Fraction(0)),
        (Fraction(0), Fraction(1, bb)),
    )
    extreme1 = (-1, 1)
    middle = (-1, 0)
    extreme2 = (-1, -1)
    left = unimodular_alpha(extreme1, middle, inverse_gram)
    right = unimodular_alpha(middle, extreme2, inverse_gram)
    value = left + right - Fraction(1, 2)
    closed_form = Fraction(aa + 2 * bb, 6 * (aa + bb))
    assert value == closed_form
    assert value >= Fraction(1, 6)
    return value


def alpha(normal1, normal2):
    index = saturation_index(normal1, normal2)
    assert index in (1, 2)
    return (index1_alpha(normal1, normal2) if index == 1
            else index2_alpha(normal1, normal2))


def show(value):
    return str(value.numerator) if value.denominator == 1 else str(value)


def main():
    global_types = set()
    global_minimum = None
    applicable_ranks = 0
    for rank in range(3, 21):
        rows = normal_rows(rank)
        histogram = Counter()
        minimum = None
        for normal1, normal2 in combinations(rows, 2):
            index = saturation_index(normal1, normal2)
            if index == 0:
                assert normal1 == tuple(-entry for entry in normal2)
                continue
            assert index in (1, 2)
            value = alpha(normal1, normal2)
            norm1 = dot(normal1, normal1)
            norm2 = dot(normal2, normal2)
            cross = dot(normal1, normal2)
            global_types.add((index, min(norm1, norm2), max(norm1, norm2), cross))
            histogram[(index, value)] += 1
            minimum = value if minimum is None else min(minimum, value)

        if minimum is None:
            assert rank == 3 and len(rows) == 2
            print("r=3 normals=2 codim2=not_applicable")
            continue

        applicable_ranks += 1
        global_minimum = (minimum if global_minimum is None
                          else min(global_minimum, minimum))
        assert minimum >= Fraction(1, 12)
        index_histogram = Counter()
        for (index, _), count in histogram.items():
            index_histogram[index] += count
        if rank == 5:
            assert index_histogram == Counter({1: 339, 2: 3})
            assert histogram[(2, Fraction(5, 18))] == 3
            assert minimum == Fraction(1, 9)
        print(
            f"r={rank} normals={len(rows)} min_alpha={show(minimum)} "
            f"index_hist={dict(sorted(index_histogram.items()))}"
        )

    assert applicable_ranks == 17
    assert global_minimum == Fraction(1, 9)
    print(
        f"PASS invariant_types={len(global_types)} "
        f"proof_bound=1/12 observed_min={show(global_minimum)}"
    )


if __name__ == "__main__":
    main()
